// Run after adding/removing a city: node scripts/generate-city-catalog.js
// Only read checked-in data; no network requests or generated POI facts.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.join(__dirname, '..');
function generateCityCatalog() {
  const catalog = {};
  for (const file of fs.readdirSync(path.join(root, 'data')).filter(f => /^[a-z0-9-]+\.js$/.test(f)).sort()) {
    const context = { window: {} };
    vm.runInNewContext(fs.readFileSync(path.join(root, 'data', file), 'utf8'), context, { timeout: 1000 });
    const key = file.slice(0, -3);
    const city = context.window.CITY_DATA && context.window.CITY_DATA[key];
    if (!city || !city.name || !city.province) throw new Error('Invalid city data: ' + file);
    catalog[key] = { province: city.province, name: city.name };
  }
  fs.writeFileSync(path.join(root, 'city-catalog.js'), '// Generated by scripts/generate-city-catalog.js; metadata only.\nwindow.CITY_CATALOG = ' + JSON.stringify(catalog, null, 2) + ';\n');
  console.log('Indexed ' + Object.keys(catalog).length + ' cities.');
  return catalog;
}
module.exports = generateCityCatalog;
if (require.main === module) generateCityCatalog();
